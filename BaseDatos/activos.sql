/*
====================================================
BASE DE DATOS - MODULO ACTIVOS
====================================================
*/

/*
====================================================
TABLA: TIPO_ACTIVO
====================================================
*/
CREATE TABLE TIPO_ACTIVO (
    CODIGO_TIPACTIVO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    DESCRIPCION VARCHAR2(200)
);

/*
====================================================
TABLA: ACTIVO
====================================================
*/
CREATE TABLE ACTIVO (
    CODIGO_ACTIVO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    DESCRIPCION VARCHAR2(250),
    FECHA_COMPRA DATE DEFAULT SYSDATE NOT NULL,
    VALOR_COMPRA NUMBER(12,2) NOT NULL,
    VIDA_UTIL NUMBER(3) NOT NULL,
    VALOR_RESIDUAL NUMBER(12,2) DEFAULT 0,
    CODIGO_TIPACTIVO NUMBER NOT NULL,

    CONSTRAINT FK_ACTIVO_TIPO
        FOREIGN KEY (CODIGO_TIPACTIVO)
        REFERENCES TIPO_ACTIVO(CODIGO_TIPACTIVO)
);

/*
====================================================
TABLA: CABECERA_DEPRECIACION
====================================================
*/
CREATE TABLE CABECERA_DEPRECIACION (
    NUMERO_DEPRECIACION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FECHA DATE DEFAULT SYSDATE NOT NULL,
    OBSERVACIONES VARCHAR2(250)
);

/*
====================================================
TABLA: DETALLE_DEPRECIACION
====================================================
*/
CREATE TABLE DETALLE_DEPRECIACION (
    ID_DETALLE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMERO_DEPRECIACION NUMBER NOT NULL,
    VALOR_DEPRECIACION NUMBER(12,2) NOT NULL,
    CODIGO_ACTIVO NUMBER NOT NULL,

    CONSTRAINT FK_DETALLE_CABECERA
        FOREIGN KEY (NUMERO_DEPRECIACION)
        REFERENCES CABECERA_DEPRECIACION(NUMERO_DEPRECIACION),

    CONSTRAINT FK_DETALLE_ACTIVO
        FOREIGN KEY (CODIGO_ACTIVO)
        REFERENCES ACTIVO(CODIGO_ACTIVO),

    CONSTRAINT UK_DEPRECIACION_ACTIVO
        UNIQUE (NUMERO_DEPRECIACION, CODIGO_ACTIVO)
);

