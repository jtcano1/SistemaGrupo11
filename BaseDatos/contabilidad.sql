CREATE TABLE TIPO_CUENTA (
    CODIGO NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL
);

CREATE TABLE CUENTA (
    CODIGO VARCHAR2(20) PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    CODIGO_TIPO_CUENTA NUMBER NOT NULL,
    CONSTRAINT FK_CUENTA_TIPO FOREIGN KEY (CODIGO_TIPO_CUENTA)
        REFERENCES TIPO_CUENTA(CODIGO)
);

CREATE TABLE CABECERA_COMPROBANTE (
    NUMERO NUMBER PRIMARY KEY,
    FECHA DATE NOT NULL,
    OBSERVACIONES VARCHAR2(200)
);

CREATE TABLE DETALLE_COMPROBANTE (
    ID_DETALLE NUMBER PRIMARY KEY,
    NUMERO_COMPROBANTE NUMBER NOT NULL,
    CODIGO_CUENTA VARCHAR2(20) NOT NULL,
    CANTIDAD_DEBE NUMBER(12,2) DEFAULT 0,
    CANTIDAD_HABER NUMBER(12,2) DEFAULT 0,
    CONSTRAINT FK_DET_CAB FOREIGN KEY (NUMERO_COMPROBANTE)
        REFERENCES CABECERA_COMPROBANTE(NUMERO),
    CONSTRAINT FK_DET_CUENTA FOREIGN KEY (CODIGO_CUENTA)
        REFERENCES CUENTA(CODIGO)
);

CREATE SEQUENCE SEQ_CABECERA_COMPROBANTE START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_DETALLE_COMPROBANTE START WITH 1 INCREMENT BY 1;

