
/*
=========================================
MODULO INVENTARIOS
=========================================
*/

-- Tabla de articulos
CREATE TABLE ARTICULO (
    CODIGO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    PRECIO NUMBER(10,2) NOT NULL,

    CONSTRAINT PK_ARTICULO
        PRIMARY KEY (CODIGO)
);

-- Tabla de tipos de movimiento
CREATE TABLE TIPO_MOVIMIENTO (
    CODIGO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    SIGNO NUMBER(2) NOT NULL,

    CONSTRAINT PK_TIPO_MOVIMIENTO
        PRIMARY KEY (CODIGO)
);

-- Cabecera del comprobante de inventario
CREATE TABLE CABECERA_INVENTARIO (
    NUMERO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    FECHA DATE NOT NULL,
    ID_TIPO_MOVIMIENTO NUMBER NOT NULL,

    CONSTRAINT PK_CABECERA_INVENTARIO
        PRIMARY KEY (NUMERO),

    CONSTRAINT FK_CAB_INV_TIPO_MOV
        FOREIGN KEY (ID_TIPO_MOVIMIENTO)
        REFERENCES TIPO_MOVIMIENTO(CODIGO)
);

-- Detalle del comprobante de inventario
CREATE TABLE DETALLE_INVENTARIO (
    ID_DETALLE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO_COMPROBANTE NUMBER NOT NULL,
    ID_ARTICULO NUMBER NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    PRECIO NUMBER(10,2) NOT NULL,

    CONSTRAINT PK_DETALLE_INVENTARIO
        PRIMARY KEY (ID_DETALLE),

    CONSTRAINT FK_DET_INV_COMPROBANTE
        FOREIGN KEY (NUMERO_COMPROBANTE)
        REFERENCES CABECERA_INVENTARIO(NUMERO),

    CONSTRAINT FK_DET_INV_ARTICULO
        FOREIGN KEY (ID_ARTICULO)
        REFERENCES ARTICULO(CODIGO)
);

