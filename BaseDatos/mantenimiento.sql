/*
=========================================
MODULO MANTENIMIENTO
=========================================
*/

CREATE TABLE ACTIVIDAD (
    CODIGO NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,

    CONSTRAINT PK_ACTIVIDAD
        PRIMARY KEY (CODIGO)
);

CREATE TABLE ACTIVOS_M (
    CODIGO NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    FECHA_COMPRA DATE NOT NULL,

    CONSTRAINT PK_ACTIVOS_M
        PRIMARY KEY (CODIGO)
);

CREATE TABLE CABECERA_MANTENIMIENTO (
    NUMERO NUMBER NOT NULL,
    FECHA DATE NOT NULL,
    RESPONSABLE VARCHAR2(100) NOT NULL,

    CONSTRAINT PK_CABECERA_MANTENIMIENTO
        PRIMARY KEY (NUMERO)
);

CREATE TABLE DETALLE_MANTENIMIENTO (
    NUMERO_MANTENIMIENTO NUMBER NOT NULL,
    CODIGO_ACTIVO NUMBER NOT NULL,
    CODIGO_ACTIVIDAD NUMBER NOT NULL,
    VALOR NUMBER(10,2) NOT NULL,

    CONSTRAINT PK_DETALLE_MANTENIMIENTO
        PRIMARY KEY (NUMERO_MANTENIMIENTO, CODIGO_ACTIVO, CODIGO_ACTIVIDAD),

    CONSTRAINT FK_DET_MANT_CABECERA
        FOREIGN KEY (NUMERO_MANTENIMIENTO)
        REFERENCES CABECERA_MANTENIMIENTO(NUMERO),

    CONSTRAINT FK_DET_MANT_ACTIVO
        FOREIGN KEY (CODIGO_ACTIVO)
        REFERENCES ACTIVOS_M(CODIGO),

    CONSTRAINT FK_DET_MANT_ACTIVIDAD
        FOREIGN KEY (CODIGO_ACTIVIDAD)
        REFERENCES ACTIVIDAD(CODIGO)
);

CREATE SEQUENCE SEQ_ACTIVIDAD START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_ACTIVOS_M START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_CABECERA_MANTENIMIENTO START WITH 1 INCREMENT BY 1;

COMMIT;