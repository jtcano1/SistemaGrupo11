    private void tblActivosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblActivosMouseClicked
        // TODO add your handling code here:
                int fila = tblActivos.getSelectedRow();
        if (fila >= 0) {
            txtCodigo.setText(tblActivos.getValueAt(fila, 0).toString());
            txtNombre.setText(tblActivos.getValueAt(fila, 1).toString());
            txtValorCompra.setText(tblActivos.getValueAt(fila, 2).toString());
            txtPeriodos.setText(tblActivos.getValueAt(fila, 3).toString());

            TipoActivo tipoSeleccionado = (TipoActivo) tblActivos.getValueAt(fila, 4);
            for (int i = 0; i < cmbTipoActivo.getItemCount(); i++) {
                if (cmbTipoActivo.getItemAt(i).getCodigo() == tipoSeleccionado.getCodigo()) {
                    cmbTipoActivo.setSelectedIndex(i);
                    break;
                }
            }
        }

    }//GEN-LAST:event_tblActivosMouseClicked

