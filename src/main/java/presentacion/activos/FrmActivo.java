     private void cargarComboTipos() {
        cmbTipoActivo.removeAllItems();
        List<TipoActivo> listaTipos = tipoActivoBL.listarTodos();
        for (TipoActivo tipo : listaTipos) {
            cmbTipoActivo.addItem(tipo);
        }
    }

    private void configurarTabla() {
        modeloTabla = new DefaultTableModel(
                new Object[]{"Código", "Nombre", "Valor Compra", "Vida Útil", "Tipo Activo"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblActivos.setModel(modeloTabla);
    }

    private void cargarDatosTabla() {
        modeloTabla.setRowCount(0);
        List<Activo> lista = activoBL.listarTodos();
        for (Activo act : lista) {
            modeloTabla.addRow(new Object[]{
                act.getId(),
                act.getNombre(),
                act.getValorCompra(),
                act.getPeriodosDepreciacion(),
                act.getTipoActivo()
            });
        }
    }

    private void limpiarCampos() {
        txtCodigo.setText("");
        txtNombre.setText("");
        txtValorCompra.setText("");
        txtPeriodos.setText("");
        if (cmbTipoActivo.getItemCount() > 0) {
            cmbTipoActivo.setSelectedIndex(0);
        }
        tblActivos.clearSelection();
    }

