    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
            Activo activo = new Activo();
            activo.setNombre(txtNombre.getText().trim());
            activo.setValorCompra(new BigDecimal(txtValorCompra.getText().trim()));
            activo.setPeriodosDepreciacion(Integer.parseInt(txtPeriodos.getText().trim()));
            activo.setTipoActivo((TipoActivo) cmbTipoActivo.getSelectedItem());

            String mensaje = activoBL.guardar(activo);
            JOptionPane.showMessageDialog(this, mensaje);
            cargarDatosTabla();
            limpiarCampos();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese valores numéricos válidos en Valor Compra y Vida Útil.");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
                if (txtCodigo.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un activo de la tabla para actualizar.");
            return;
        }
        try {
            Activo activo = new Activo();
            activo.setId(Integer.parseInt(txtCodigo.getText()));
            activo.setNombre(txtNombre.getText().trim());
            activo.setValorCompra(new BigDecimal(txtValorCompra.getText().trim()));
            activo.setPeriodosDepreciacion(Integer.parseInt(txtPeriodos.getText().trim()));
            activo.setTipoActivo((TipoActivo) cmbTipoActivo.getSelectedItem());

            String mensaje = activoBL.actualizar(activo);
            JOptionPane.showMessageDialog(this, mensaje);
            cargarDatosTabla();
            limpiarCampos();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Verifique que los valores numéricos sean correctos.");
        }

    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
                if (txtCodigo.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un activo de la tabla para eliminar.");
            return;
        }
        int confirm = JOptionPane.showConfirmDialog(this, "¿Desea eliminar este activo?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            String mensaje = activoBL.eliminar(Integer.parseInt(txtCodigo.getText()));
            JOptionPane.showMessageDialog(this, mensaje);
            cargarDatosTabla();
            limpiarCampos();
        }

    }//GEN-LAST:event_jButton3ActionPerformed

