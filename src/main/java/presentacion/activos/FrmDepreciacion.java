     private void configurarTabla() {
        modeloTabla = new DefaultTableModel(
                new Object[]{"Código", "Activo", "Valor Compra", "Vida Útil", "Cuota Mensual Est."}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblPreview.setModel(modeloTabla);
    }

    private void cargarVistaPreviaActivos() {
        modeloTabla.setRowCount(0);
        List<Activo> lista = activoBL.listarTodos();
        for (Activo act : lista) {
            BigDecimal cuota = act.getValorCompra()
                    .divide(new BigDecimal(act.getPeriodosDepreciacion()), 2, RoundingMode.HALF_UP);
            modeloTabla.addRow(new Object[]{
                act.getId(),
                act.getNombre(),
                act.getValorCompra(),
                act.getPeriodosDepreciacion(),
                cuota
            });
        }
    }

