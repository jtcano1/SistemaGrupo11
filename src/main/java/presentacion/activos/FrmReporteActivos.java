    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
                try {
            Date inicio = Date.valueOf(txtFechaInicio.getText().trim());
            Date fin = Date.valueOf(txtFechaFin.getText().trim());

            modeloFechas.setRowCount(0);
            List<Object[]> lista = activoBL.obtenerReporteDepreciadosPorFecha(inicio, fin);

            if (lista.isEmpty()) {
                JOptionPane.showMessageDialog(this, "No se encontraron depreciaciones en ese rango de fechas.");
                return;
            }

            for (Object[] fila : lista) {
                modeloFechas.addRow(fila);
            }
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, "Formato de fecha inválido. Use AAAA-MM-DD (ej. 2026-11-01).");
        }

    }//GEN-LAST:event_jButton1ActionPerformed

