     private void configurarTablas() {
        modeloFechas = new DefaultTableModel(
                new Object[]{"Código", "Activo", "Total Depreciado ($)"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblReporteFechas.setModel(modeloFechas);

        modeloTipos = new DefaultTableModel(
                new Object[]{"Tipo de Activo", "Cantidad Registrada"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblReporteTipos.setModel(modeloTipos);
    }

    private void cargarReporteTipos() {
        modeloTipos.setRowCount(0);
        Map<String, Integer> datos = activoBL.obtenerReportePorTipo();
        for (Map.Entry<String, Integer> fila : datos.entrySet()) {
            modeloTipos.addRow(new Object[]{fila.getKey(), fila.getValue()});
        }
    }

