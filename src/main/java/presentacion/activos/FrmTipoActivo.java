    private void configurarTabla() {
        modeloTabla = new DefaultTableModel(new Object[]{"Código", "Nombre"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Evita que editen directamente en la celda
            }
        };
        tblTipos.setModel(modeloTabla);
    }

    private void cargarDatosTabla() {
        modeloTabla.setRowCount(0); // Limpia la tabla
        List<TipoActivo> lista = tipoActivoBL.listarTodos();
        for (TipoActivo tipo : lista) {
            modeloTabla.addRow(new Object[]{tipo.getCodigo(), tipo.getNombre()});
        }
    }

    private void limpiarCampos() {
        txtCodigo.setText("");
        txtNombre.setText("");
        tblTipos.clearSelection();
}
    

