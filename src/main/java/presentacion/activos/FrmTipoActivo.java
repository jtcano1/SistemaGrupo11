    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        TipoActivo tipo = new TipoActivo();
        tipo.setNombre(txtNombre.getText().trim());
        tipo.setCuentaGasto(txtCuentaGasto.getText().trim());
        tipo.setCuentaDepAcumulada(txtCuentaDepAcumulada.getText().trim());


        String mensaje = tipoActivoBL.guardar(tipo);
        JOptionPane.showMessageDialog(this, mensaje);
        cargarDatosTabla();
        limpiarCampos();
        txtCuentaGasto.setText("");
        txtCuentaDepAcumulada.setText("");
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        if (txtCodigo.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un registro de la tabla para actualizar.");
            return;
        }
        TipoActivo tipo = new TipoActivo();
        tipo.setCodigo(Integer.parseInt(txtCodigo.getText()));
        tipo.setNombre(txtNombre.getText().trim());

        String mensaje = tipoActivoBL.actualizar(tipo);
        JOptionPane.showMessageDialog(this, mensaje);
        cargarDatosTabla();
        limpiarCampos();
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        
        if (txtCodigo.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un registro de la tabla para eliminar.");
            return;
        }
        int confirmacion = JOptionPane.showConfirmDialog(this, "¿Seguro que desea eliminar este tipo de activo?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (confirmacion == JOptionPane.YES_OPTION) {
            int codigo = Integer.parseInt(txtCodigo.getText());
            String mensaje = tipoActivoBL.eliminar(codigo);
            JOptionPane.showMessageDialog(this, mensaje);
            cargarDatosTabla();
            limpiarCampos();
        }
    }//GEN-LAST:event_jButton3ActionPerformed

